def preprocess_binary(images, labels):

    # Convert RGB to grayscale
    images = tf.image.rgb_to_grayscale(images)

    # Normalize to 0-1
    images = tf.cast(images, tf.float32) / 255.0

    # ECG trace is darker than the white background
    # Keep darker pixels as ECG signal
