import tensorflow as tf
import numpy as np
import matplotlib.pyplot as plt

# =========================================================
# 1. Validate the trained model and input shape
# =========================================================

INPUT_SHAPE = (224, 224, 1)

# Make sure the model has been built.
_ = final_model(
    tf.zeros((1, *INPUT_SHAPE), dtype=tf.float32),
    training=False
)

# Find the last Conv2D layer.
conv_layers = [
    layer for layer in final_model.layers
    if isinstance(layer, tf.keras.layers.Conv2D)
]

if not conv_layers:
    raise ValueError(
        "No Conv2D layer found. Check the architecture of final_model."
    )

last_conv_layer = conv_layers[-1]
print("Grad-CAM layer:", last_conv_layer.name)

# =========================================================
# 2. Explicitly construct a Grad-CAM model
#    This avoids accessing final_model.output directly.
# =========================================================

grad_input = tf.keras.Input(shape=INPUT_SHAPE)
x = grad_input
conv_features = None

for layer in final_model.layers:
    x = layer(x)

    if layer is last_conv_layer:
        conv_features = x

if conv_features is None:
    raise ValueError("Could not extract the convolutional features.")

grad_model = tf.keras.Model(
    inputs=grad_input,
    outputs=[conv_features, x]
)

# =========================================================
# 3. Grad-CAM heatmap function
# =========================================================

def make_gradcam_heatmap(image, model):
    """
    image: Tensor with shape (1, 224, 224, 1)
    model: Grad-CAM model returning convolutional features
           and class predictions.
    """

    image = tf.cast(image, tf.float32)

    with tf.GradientTape() as tape:
        conv_outputs, predictions = model(
            image, training=False
        )

        predicted_class = tf.argmax(
            predictions[0], axis=-1
        )

        class_score = predictions[:, predicted_class]

    gradients = tape.gradient(class_score, conv_outputs)

    if gradients is None:
        raise ValueError(
            "Gradients are None. Check the model architecture."
        )

    # Global average pooling of gradients.
    weights = tf.reduce_mean(
        gradients, axis=(1, 2)
    )

    conv_outputs = conv_outputs[0]
    weights = weights[0]

    # Weighted combination of convolutional feature maps.
    heatmap = tf.reduce_sum(
        conv_outputs * weights,
        axis=-1
    )

    # Keep positive contributions.
    heatmap = tf.maximum(heatmap, 0)

    # Normalize the heatmap to [0, 1].
    max_value = tf.reduce_max(heatmap)

    heatmap = tf.cond(
        max_value > 0,
        lambda: heatmap / (max_value + 1e-8),
        lambda: tf.zeros_like(heatmap)
    )

    return heatmap.numpy(), int(predicted_class.numpy())


